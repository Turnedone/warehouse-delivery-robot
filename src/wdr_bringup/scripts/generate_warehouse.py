#!/usr/bin/env python3
"""Generates the warehouse world, map, filter masks and station files from one layout file.

Keeping a single layout file means the Gazebo world, the occupancy map that AMCL localises
against, and the Nav2 filter masks can never drift apart: they are all rasterised from the
same rectangles.

    generate_warehouse.py                 regenerate into the package directories
    generate_warehouse.py --check         exit 1 if a committed file differs from a fresh build
    generate_warehouse.py --out-dir DIR   write somewhere else (used by the tests)
"""

import argparse
import filecmp
import math
import os
import sys
import tempfile

import yaml

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_LAYOUT = os.path.join(PKG_DIR, 'config', 'warehouse_layout.yaml')

# map_server trinary values (PGM pixels, negate: 0)
OCCUPIED = 0
FREE = 254
UNKNOWN = 205

GENERATED_FILES = [
    'worlds/warehouse.sdf',
    'maps/warehouse.pgm', 'maps/warehouse.yaml',
    'maps/keepout_mask.pgm', 'maps/keepout_mask.yaml',
    'maps/speed_mask.pgm', 'maps/speed_mask.yaml',
    'config/stations.yaml', 'config/docks.yaml', 'config/obstacles.yaml',
]

HEADER = '# GENERATED by scripts/generate_warehouse.py from config/warehouse_layout.yaml. Do not edit.\n'


class Grid:
    """A row-major image whose row 0 is the top (highest y), as PGM files store it."""

    def __init__(self, layout, fill):
        m = layout['map']
        self.res = m['resolution']
        sx, sy = layout['building']['size']
        self.origin_x = -m['margin']
        self.origin_y = -m['margin']
        self.width = int(round((sx + 2 * m['margin']) / self.res))
        self.height = int(round((sy + 2 * m['margin']) / self.res))
        self.pixels = bytearray([fill]) * (self.width * self.height)

    def fill_rect(self, min_x, min_y, max_x, max_y, value):
        """Sets every cell whose centre lies inside the rectangle."""
        c0 = max(0, int(math.ceil((min_x - self.origin_x) / self.res - 0.5)))
        c1 = min(self.width - 1, int(math.floor((max_x - self.origin_x) / self.res - 0.5)))
        r0 = max(0, int(math.ceil((min_y - self.origin_y) / self.res - 0.5)))
        r1 = min(self.height - 1, int(math.floor((max_y - self.origin_y) / self.res - 0.5)))
        for row in range(r0, r1 + 1):
            img_row = self.height - 1 - row
            start = img_row * self.width
            self.pixels[start + c0:start + c1 + 1] = bytes([value]) * (c1 - c0 + 1)

    def write_pgm(self, path):
        with open(path, 'wb') as f:
            f.write(b'P5\n%d %d\n255\n' % (self.width, self.height))
            f.write(bytes(self.pixels))

    def map_yaml(self, image, mode, occupied_thresh, free_thresh):
        return (HEADER +
                f'image: {image}\n'
                f'mode: {mode}\n'
                f'resolution: {self.res}\n'
                f'origin: [{self.origin_x}, {self.origin_y}, 0.0]\n'
                'negate: 0\n'
                f'occupied_thresh: {occupied_thresh}\n'
                f'free_thresh: {free_thresh}\n')


def box_rect(box):
    cx, cy, sx, sy, _ = box
    return cx - sx / 2, cy - sy / 2, cx + sx / 2, cy + sy / 2


def wall_boxes(layout):
    sx, sy = layout['building']['size']
    t = layout['building']['wall_thickness']
    h = layout['building']['wall_height']
    return [
        ('wall_south', [sx / 2, -t / 2, sx + 2 * t, t, h]),
        ('wall_north', [sx / 2, sy + t / 2, sx + 2 * t, t, h]),
        ('wall_west', [-t / 2, sy / 2, t, sy, h]),
        ('wall_east', [sx + t / 2, sy / 2, t, sy, h]),
    ]


def speed_pixel(percent):
    """PGM value that map_server (mode: scale, free 0.0, occupied 1.0) loads as `percent`.

    map_server computes occ = (255 - pixel) / 255 and then rint(occ * 100), so we pick the
    pixel whose occupancy rounds back to exactly `percent`.
    """
    if not 1 <= percent <= 100:
        raise ValueError(f'speed zone percent must be 1..100, got {percent}')
    pixel = int(round(255 * (1 - percent / 100.0)))
    assert round((255 - pixel) / 255.0 * 100) == percent
    return pixel


# ---------------------------------------------------------------- SDF -------------------

def sdf_box_model(name, box, color, static=True, collide=True, z0=0.0):
    cx, cy, sx, sy, h = box
    r, g, b = color
    collision = (f"""
        <collision name="collision">
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
        </collision>""" if collide else '')
    return f"""
    <model name="{name}">
      <static>{'true' if static else 'false'}</static>
      <pose>{cx} {cy} {z0 + h / 2} 0 0 0</pose>
      <link name="link">{collision}
        <visual name="visual">
          <geometry><box><size>{sx} {sy} {h}</size></box></geometry>
          <material>
            <ambient>{r} {g} {b} 1</ambient>
            <diffuse>{r} {g} {b} 1</diffuse>
          </material>
        </visual>
      </link>
    </model>"""


def floor_marking(name, rect, color, z=0.002):
    min_x, min_y, max_x, max_y = rect
    box = [(min_x + max_x) / 2, (min_y + max_y) / 2, max_x - min_x, max_y - min_y, 0.002]
    return sdf_box_model(name, box, color, collide=False, z0=z - 0.001)


def build_sdf(layout):
    parts = []
    for name, box in wall_boxes(layout):
        parts.append(sdf_box_model(name, box, [0.8, 0.8, 0.78]))
    for obj in layout['objects']:
        parts.append(sdf_box_model(obj['name'], obj['box'], obj.get('color', [0.5, 0.5, 0.5])))
    # Floor markings: red keep-out, yellow slow zones, blue station pads, green dock pad.
    for zone in layout['keepout_zones']:
        parts.append(floor_marking('keepout_' + zone['name'], zone['rect'], [0.8, 0.1, 0.1]))
    for zone in layout['speed_zones']:
        parts.append(floor_marking('slow_' + zone['name'], zone['rect'], [0.9, 0.8, 0.2], z=0.001))
    for st in layout['stations']:
        x, y, _ = st['pose']
        parts.append(floor_marking('pad_' + st['name'], [x - 0.3, y - 0.3, x + 0.3, y + 0.3],
                                   [0.2, 0.4, 0.9], z=0.003))
    for dock in layout['docks']:
        x, y, _ = dock['pose']
        parts.append(floor_marking('pad_' + dock['name'], [x - 0.3, y - 0.3, x + 0.3, y + 0.3],
                                   [0.1, 0.7, 0.2], z=0.003))
    # Moving obstacles start at the first point of their path. They are static models that
    # obstacle_mover teleports along the path: the lidar sees them, physics does not push them.
    for ob in layout['moving_obstacles']:
        x, y = ob['path'][0]
        sx, sy, h = ob['size']
        parts.append(sdf_box_model(ob['name'], [x, y, sx, sy, h], ob['color']))

    sx, sy = layout['building']['size']
    return f"""<?xml version="1.0"?>
<!-- GENERATED by scripts/generate_warehouse.py from config/warehouse_layout.yaml. Do not edit. -->
<sdf version="1.9">
  <world name="{layout['world_name']}">
    <physics name="2ms" type="ode">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>500</real_time_update_rate>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>

    <scene>
      <ambient>0.8 0.8 0.8 1</ambient>
      <background>0.7 0.75 0.8 1</background>
      <shadows>false</shadows>
      <grid>false</grid>
    </scene>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>{sx / 2} {sy / 2} 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{sx + 10} {sy + 10}</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{sx + 10} {sy + 10}</size></plane></geometry>
          <material>
            <ambient>0.45 0.45 0.45 1</ambient>
            <diffuse>0.45 0.45 0.45 1</diffuse>
          </material>
        </visual>
      </link>
      <pose>{sx / 2} {sy / 2} 0 0 0 0</pose>
    </model>
{''.join(parts)}
  </world>
</sdf>
"""


# ---------------------------------------------------------------- YAML side files -------

def dump(data):
    return HEADER + yaml.safe_dump(data, sort_keys=False, default_flow_style=None)


def stations_yaml(layout):
    stations = {}
    for st in layout['stations']:
        x, y, yaw = st['pose']
        stations[st['name']] = {'type': st['type'], 'x': x, 'y': y, 'yaw': yaw}
    for dock in layout['docks']:
        x, y, yaw = dock['pose']
        stations[dock['name']] = {'type': 'dock', 'x': x, 'y': y, 'yaw': yaw}
    return dump({'frame_id': 'map', 'stations': stations})


def docks_yaml(layout):
    # opennav_docking's dock database file format
    docks = {}
    for dock in layout['docks']:
        docks[dock['name']] = {'type': dock['type'], 'frame': 'map', 'pose': list(dock['pose'])}
    return dump({'docks': docks})


def obstacles_yaml(layout):
    obstacles = []
    for ob in layout['moving_obstacles']:
        obstacles.append({'name': ob['name'], 'speed': ob['speed'], 'height': ob['size'][2],
                          'path': [list(p) for p in ob['path']]})
    return dump({'world_name': layout['world_name'], 'obstacles': obstacles})


# ---------------------------------------------------------------- main ------------------

def generate(layout, out_dir):
    for sub in ('worlds', 'maps', 'config'):
        os.makedirs(os.path.join(out_dir, sub), exist_ok=True)

    def write(rel, text):
        with open(os.path.join(out_dir, rel), 'w', newline='\n') as f:
            f.write(text)

    write('worlds/warehouse.sdf', build_sdf(layout))

    # Occupancy map: unknown outside, free inside, walls and objects occupied.
    occ = Grid(layout, UNKNOWN)
    sx, sy = layout['building']['size']
    occ.fill_rect(0.0, 0.0, sx, sy, FREE)
    for _, box in wall_boxes(layout):
        occ.fill_rect(*box_rect(box), OCCUPIED)
    for obj in layout['objects']:
        if obj.get('in_map', True):
            occ.fill_rect(*box_rect(obj['box']), OCCUPIED)
    occ.write_pgm(os.path.join(out_dir, 'maps/warehouse.pgm'))
    write('maps/warehouse.yaml', occ.map_yaml('warehouse.pgm', 'trinary', 0.65, 0.25))

    # Keep-out mask: occupied (lethal for the KeepoutFilter) inside keep-out zones, grown by
    # keepout_margin so the whole robot, not just its centre, stays out.
    keepout = Grid(layout, FREE)
    margin = layout.get('keepout_margin', 0.0)
    for zone in layout['keepout_zones']:
        min_x, min_y, max_x, max_y = zone['rect']
        keepout.fill_rect(min_x - margin, min_y - margin, max_x + margin, max_y + margin,
                          OCCUPIED)
    keepout.write_pgm(os.path.join(out_dir, 'maps/keepout_mask.pgm'))
    write('maps/keepout_mask.yaml', keepout.map_yaml('keepout_mask.pgm', 'trinary', 0.65, 0.25))

    # Speed mask: value = percent of maximum speed, 0 = no limit (255 white).
    speed = Grid(layout, 255)
    for zone in layout['speed_zones']:
        speed.fill_rect(*zone['rect'], speed_pixel(zone['percent']))
    speed.write_pgm(os.path.join(out_dir, 'maps/speed_mask.pgm'))
    write('maps/speed_mask.yaml', speed.map_yaml('speed_mask.pgm', 'scale', 1.0, 0.0))

    write('config/stations.yaml', stations_yaml(layout))
    write('config/docks.yaml', docks_yaml(layout))
    write('config/obstacles.yaml', obstacles_yaml(layout))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--layout', default=DEFAULT_LAYOUT)
    parser.add_argument('--out-dir', default=PKG_DIR)
    parser.add_argument('--check', action='store_true',
                        help='compare a fresh build against the files in --out-dir')
    args = parser.parse_args()

    with open(args.layout) as f:
        layout = yaml.safe_load(f)

    if not args.check:
        generate(layout, args.out_dir)
        print(f'generated {len(GENERATED_FILES)} files in {args.out_dir}')
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        generate(layout, tmp)
        stale = [rel for rel in GENERATED_FILES
                 if not os.path.exists(os.path.join(args.out_dir, rel))
                 or not filecmp.cmp(os.path.join(tmp, rel), os.path.join(args.out_dir, rel),
                                    shallow=False)]
    if stale:
        print('out of date (run scripts/generate_warehouse.py):', ', '.join(stale))
        return 1
    print('generated files are up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
